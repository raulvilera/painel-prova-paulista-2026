function limpar(texto, max) {
  return String(texto == null ? '' : texto)
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, '')
    .replace(/\r\n?/g, '\n')
    .trim()
    .slice(0, max);
}

/* Lê os campos de identificação. Devolve {registro} (pronto para enviar), {semRegistro:true} ou {erro}. */
function lerIdentificacao(body, id) {
  const extras = ['turma', 'aluno', 'dissertativas', 'envioId'].filter(k => Object.prototype.hasOwnProperty.call(body, k));
  if (!extras.length) return { semRegistro: true };
  if (extras.length !== 4) return { erro: 'Para registrar na planilha, envie turma, aluno, dissertativas e envioId.' };
  const partes = /^(bio|qui)-([23])-(paulista|provao)$/.exec(id);
  if (!partes) return { erro: 'Avaliação desconhecida.' };
  const componente = COMPONENTES[partes[1]];
  const turma = Object.prototype.hasOwnProperty.call(TURMAS, body.turma) ? TURMAS[body.turma] : null;
  if (!turma) return { erro: 'Turma desconhecida.' };
  if (turma.serie !== partes[2] || !turma.componentes.includes(componente.chave)) {
    return { erro: 'Esta avaliação não pertence à turma escolhida.' };
  }
  const lista = ALUNOS[body.turma] || [];
  const aluno = Number.isInteger(body.aluno) ? lista.find(a => a.n === body.aluno) : null;
  if (!aluno) return { erro: 'Escolha seu nome na lista da turma para registrar na planilha.' };
  if (typeof body.envioId !== 'string' || !/^[A-Za-z0-9-]{8,64}$/.test(body.envioId)) return { erro: 'Identificador de envio inválido.' };
  const dis = body.dissertativas;
  if (!Array.isArray(dis) || dis.length !== N_DISSERTATIVAS || !dis.every(x => typeof x === 'string')) {
    return { erro: 'Envie as 2 respostas dissertativas.' };
  }
  const textos = dis.map(x => limpar(x, 3000));
  if (textos.some(x => !x)) return { erro: 'Responda as 2 questões dissertativas antes de entregar.' };
  const dissertativas = textos.map((resposta, k) => {
    const qid = id + '-' + (QID_DIS_BASE + k + 1);
    return { resposta, qid, contexto: CONTEXTO_DIS[qid] || '' };
  });
  if (dissertativas.some(d => !d.contexto)) return { erro: 'Critérios da dissertativa não encontrados.' };
  return {
    registro: {
      envioId: body.envioId,
      turmaId: body.turma,
      turma: turma.label,
      componente: componente.label,
      prova: PROVAS[partes[3]],
      n: aluno.n,
      nome: aluno.nome,
      ra: aluno.ra,
      dissertativas
    }
  };
}

async function registrarNaPlanilha(dados) {
  const url = process.env.EM_APPS_SCRIPT_URL || '';
  const segredo = process.env.EM_SEGREDO || '';
  if (!url || !segredo) return { ok: false, motivo: 'nao-configurado' };
  const controle = new AbortController();
  const relogio = setTimeout(() => controle.abort(), TEMPO_REGISTRO_MS);
  try {
    const resposta = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'text/plain;charset=utf-8' },
      body: JSON.stringify(Object.assign({ acao: 'enviarEM', segredo }, dados)),
      redirect: 'follow',
      signal: controle.signal
    });
    const texto = await resposta.text();
    let retorno = null;
    try { retorno = JSON.parse(texto); } catch (e) {
      const login = /accounts\.google|ServiceLogin|Fazer login|Sign in/i.test(texto);
      return { ok: false, motivo: 'indisponivel', detalhe: login ? 'HTTP ' + resposta.status + ': o Google pediu login (implantação não está como "Qualquer pessoa")' : 'HTTP ' + resposta.status + ': resposta não é JSON (' + limpar(texto, 60) + ')' };
    }
    if (!(retorno && retorno.ok === true)) return { ok: false, motivo: 'recusado', detalhe: limpar(retorno && retorno.erro, 120) };
    return { ok: true, dissertativas: Array.isArray(retorno.dissertativas) ? retorno.dissertativas : null };
  } catch (erro) {
    return { ok: false, motivo: 'indisponivel', detalhe: erro && erro.name === 'AbortError' ? 'tempo esgotado' : 'falha de rede: ' + limpar(erro && erro.message, 80) };
  } finally {
    clearTimeout(relogio);
  }
}

/* Guarda o resultado do aluno no Supabase (para o dashboard do professor). Nunca derruba o envio: se falhar, só não aparece no dashboard. */
async function gravarResultado(ident, id, q, respostas, acertos, notaObjetiva, dissertativas, notaFinal) {
  const base = (process.env.SUPABASE_URL || '').replace(/\/$/, ''), chave = process.env.SUPABASE_SERVICE_KEY || '';
  if (!base || !chave || !ident || !ident.registro) return;
  const r = ident.registro;
  const itens = q.map((item, i) => ({ id: item.id, tipo: 'obj', resp: 'ABCDE'[respostas[i]], acerto: respostas[i] === item.correta }))
    .concat((dissertativas || []).map((d, k) => ({ id: id + '-' + (QID_DIS_BASE + k + 1), tipo: 'dis', nota: d.nota, status: d.status })));
  const linha = { envio_id: r.envioId, avaliacao: id, turma_id: r.turmaId, turma: r.turma, componente: r.componente, prova: r.prova, n: r.n, nome: r.nome, ra: r.ra || '',
    itens, acertos, total_obj: q.length, nota_obj: notaObjetiva, nota_final: notaFinal, status: notaFinal === null ? 'pendente' : 'corrigido pela IA' };
  try {
    const c = new AbortController(), t = setTimeout(() => c.abort(), 6000);
    await fetch(base + '/rest/v1/em_respostas?on_conflict=envio_id', { method: 'POST', signal: c.signal,
      headers: { apikey: chave, Authorization: 'Bearer ' + chave, 'Content-Type': 'application/json', Prefer: 'resolution=merge-duplicates,return=minimal' }, body: JSON.stringify(linha) });
    clearTimeout(t);
  } catch (e) { /* silencioso */ }
}

module.exports = async function corrigirEM(req, res) {
  res.setHeader('Cache-Control', 'no-store');
  res.setHeader('X-Content-Type-Options', 'nosniff');
  res.setHeader('Content-Type', 'application/json; charset=utf-8');
  const reply = (status, value) => res.status(status).json(value);
  if (req.method !== 'POST') {
    res.setHeader('Allow', 'POST');
    return reply(405, {ok:false, erro:'Use POST para entregar a avaliação.'});
  }
  try {
    const contentLength = Number(req.headers && req.headers['content-length'] || 0);
    if (contentLength > MAX_CORPO) return reply(413, {ok:false, erro:'Solicitação muito grande.'});
    let body = req.body;
    if (typeof body === 'string') {
      if (Buffer.byteLength(body, 'utf8') > MAX_CORPO) return reply(413, {ok:false, erro:'Solicitação muito grande.'});
      body = JSON.parse(body);
    }
    if (!body || typeof body !== 'object' || Array.isArray(body)) return reply(400, {ok:false, erro:'Solicitação inválida.'});
    const permitidas = ['avaliacao', 'respostas', 'turma', 'aluno', 'dissertativas', 'envioId'];
    if (!Object.keys(body).every(k => permitidas.includes(k)) || !('avaliacao' in body) || !('respostas' in body)) {
      return reply(400, {ok:false, erro:'Solicitação inválida: campos não reconhecidos.'});
    }
    const id = body.avaliacao;
    if (typeof id !== 'string' || !Object.prototype.hasOwnProperty.call(GABARITO, id)) return reply(400, {ok:false, erro:'Avaliação desconhecida.'});
    const q = GABARITO[id], respostas = body.respostas;
    if (!Array.isArray(respostas) || respostas.length !== q.length || !respostas.every(r => Number.isInteger(r) && r >= 0 && r <= 4)) {
      return reply(422, {ok:false, erro:'Responda todas as questões objetivas antes de entregar.'});
    }
    const ident = lerIdentificacao(body, id);
    if (ident.erro) return reply(422, {ok:false, erro:ident.erro});

    const devolutiva = q.map((item, i) => ({
      id:item.id, resposta:respostas[i], correta:item.correta,
      acertou:respostas[i] === item.correta, justificativa:item.justificativa,
      objeto:item.objeto, referencia:item.referencia
    }));
    const acertos = devolutiva.filter(x => x.acertou).length;
    const notaObjetiva = Math.round(acertos / q.length * 100) / 10;

    let registro = { ok: false, motivo: 'sem-identificacao' };
    if (ident.registro) {
      registro = await registrarNaPlanilha(Object.assign({}, ident.registro, {
        avaliacao: id,
        respostas: respostas.map(r => 'ABCDE'[r]),
        gabarito: q.map(item => 'ABCDE'[item.correta]),
        acertos, total: q.length, notaObjetiva
      }));
    }
    // Correção das dissertativas pela IA (feita no Apps Script com os descritores). Nota 0–1 cada; provisória até o professor revisar.
    let dissertativas = null, notaFinal = null;
    if (registro.ok && registro.dissertativas && registro.dissertativas.length === N_DISSERTATIVAS) {
      dissertativas = registro.dissertativas.map(d => {
        const nota = d && d.status === 'corrigido' && typeof d.nota === 'number' && d.nota >= 0 && d.nota <= 1 ? Math.round(d.nota * 10) / 10 : null;
        return { nota, comentario: nota === null ? '' : limpar(d.comentario, 500), status: nota === null ? 'pendente' : 'corrigido' };
      });
      if (dissertativas.every(d => d.nota !== null)) {
        notaFinal = Math.round((acertos + dissertativas[0].nota + dissertativas[1].nota) / (q.length + N_DISSERTATIVAS) * 100) / 10;
      }
    }
    await gravarResultado(ident, id, q, respostas, acertos, notaObjetiva, dissertativas, notaFinal);
    delete registro.dissertativas;
    let mensagem;
    if (!registro.ok) mensagem = 'Nota das objetivas. Não foi possível registrar na planilha: tente registrar de novo ou entregue o comprovante ao professor. As dissertativas serão corrigidas pelo professor.';
    else if (notaFinal !== null) mensagem = 'Resultado registrado na planilha do professor. Nota final provisória calculada com a correção automática das dissertativas; o professor pode revisá-la.';
    else mensagem = 'Resultado registrado na planilha do professor. A correção automática das dissertativas ainda está pendente; a nota final sai depois.';
    return reply(200, {ok:true, avaliacao:id, acertos, total:q.length,
      notaObjetiva, dissertativas, notaFinal, devolutiva, registro, mensagem});
  } catch (error) {
    return reply(400, {ok:false, erro:'Não foi possível interpretar a solicitação. Revise as respostas e tente novamente.'});
  }
};
